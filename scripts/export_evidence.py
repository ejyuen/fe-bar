def pipeline_md():
    pid, name = pipeline_id()
    w = ws()
    ups = w.pipelines.list_updates(pid, max_results=5).updates or []
    out = header("02 - Lakeflow pipeline run")
    out += f"Pipeline: `{name}` (id `{pid}`)\n\n### Recent updates (Pipelines API)\n\n"
    rows = []
    for u in ups:
        ts = datetime.datetime.fromtimestamp(u.creation_time / 1000, datetime.timezone.utc).strftime("%Y-%m-%d %H:%M:%S") if u.creation_time else ""
        rows.append({"update_id": u.update_id, "state": u.state.value if u.state else "", "cause": u.cause.value if u.cause else "",
                     "full_refresh": u.full_refresh, "created_utc": ts})
    import pandas as pd
    out += md(pd.DataFrame(rows)) + "\n\n"
    latest_ok = next((u.update_id for u in ups if u.state and u.state.value == "COMPLETED"), None)
    out += f"Latest COMPLETED update: `{latest_ok}`\n\n"
    out += section("Expectation results per dataset (event log, all updates)", f"""
WITH ev AS (
  SELECT origin.update_id, origin.flow_name,
         explode(from_json(details:flow_progress.data_quality.expectations::string,
                 'array<struct<name:string,dataset:string,passed_records:bigint,failed_records:bigint>>')) AS e
  FROM event_log('{pid}')
  WHERE event_type = 'flow_progress' AND details:flow_progress.data_quality.expectations IS NOT NULL)
SELECT update_id, e.dataset, e.name AS expectation, sum(e.passed_records) AS passed, sum(e.failed_records) AS failed
FROM ev GROUP BY ALL ORDER BY update_id, dataset, expectation""")
    out += section("Flow completion events for the latest completed update", f"""
SELECT timestamp, origin.flow_name, details:flow_progress.status::string AS status,
       details:flow_progress.metrics.num_output_rows::bigint AS num_output_rows
FROM event_log('{pid}')
WHERE event_type = 'flow_progress' AND origin.update_id = '{latest_ok}'
  AND details:flow_progress.status::string IN ('COMPLETED', 'FAILED')
ORDER BY timestamp""")
    out += section("Update state transitions (latest completed update)", f"""
SELECT timestamp, message FROM event_log('{pid}')
WHERE event_type = 'update_progress' AND origin.update_id = '{latest_ok}' ORDER BY timestamp""")
    union = "\nUNION ALL ".join(f"SELECT '{t}' AS table_name, count(*) AS row_count FROM {CATALOG}.{t}" for t in TABLES)
    out += section("Row counts (queried as admin)", union)
    out += section("Parse status / truncation", f"""
SELECT (SELECT count(*) FROM {CATALOG}.raw.bronze_documents) AS bronze_docs,
       (SELECT count(*) FROM {CATALOG}.curated.silver_parsed) AS parsed_ok_docs,
       (SELECT sum(page_count) FROM {CATALOG}.curated.silver_parsed) AS pages,
       (SELECT count(*) FROM {CATALOG}.curated.silver_parsed WHERE parse_error IS NOT NULL) AS docs_with_page_errors,
       (SELECT count_if(truncated) FROM {CATALOG}.curated.int_doc_extracted) AS truncated_docs""")
    out += section("Idempotency check: duplicate keys after repeated setup_job / pipeline runs (expect 0)", f"""
SELECT (SELECT count(*) - count(DISTINCT doc_id) FROM {CATALOG}.raw.bronze_documents) AS dup_bronze_doc_ids,
       (SELECT count(*) - count(DISTINCT doc_id) FROM {CATALOG}.curated.silver_parsed) AS dup_silver_doc_ids,
       (SELECT count(*) - count(DISTINCT clause_id) FROM {CATALOG}.curated.gold_clauses) AS dup_clause_ids,
       (SELECT count(*) - count(DISTINCT flag_id) FROM {CATALOG}.curated.gold_risk_flags) AS dup_flag_ids""")
    out += section("gold_cost_metrics", f"SELECT * FROM {CATALOG}.curated.gold_cost_metrics ORDER BY run_id, stage")
    out += ("_Cost note: AI Functions do not return token usage, so tokens are estimated as characters/4 and "
            "unit prices are illustrative configuration values in `resources/pipeline.yml`._\n")
    write("02_pipeline_run.md", out)


