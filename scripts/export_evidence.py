def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--phase", nargs="*", type=int, default=[1])
    ap.add_argument("--skip-restricted", action="store_true")
    a = ap.parse_args()
    os.makedirs(EVID, exist_ok=True)
    if 1 in a.phase:
        pipeline_md()
        samples_md()
        governance_md(a.skip_restricted)
    if 2 in a.phase:
        eval_md()
    if 3 in a.phase:
        lakebase_md()


if __name__ == "__main__":
    main()
