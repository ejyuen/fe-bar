"""Regenerate the text execution evidence in /evidence from the live workspace.

Usage:  .venv/bin/python scripts/export_evidence.py [--phase 1 2 3 4] [--skip-restricted]

Everything written here comes from real queries/API calls at run time.
"""
import argparse
import datetime
import json
import os
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from databricks.sdk.service import iam  # noqa: E402

import dbx  # noqa: E402
from dbx import CATALOG, md, section, sql, ws  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EVID = os.path.join(ROOT, "evidence")
GOV_GROUPS = ["legal_admins", "legal_reviewers_full"]
PIPELINE_NAME = "matter-intelligence-pipeline"


def now():
    return datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")


def header(title):
    return (f"# {title}\n\n_Generated by `scripts/export_evidence.py` at {now()} from workspace "
            f"`{ws().config.host}`, catalog `{CATALOG}`. All tables below are real query output._\n\n")


def write(name, text):
    p = os.path.join(EVID, name)
    with open(p, "w") as f:
        f.write(text)
    print(f"wrote {p} ({len(text):,} chars)")


# ---------------------------------------------------------------- groups (restricted-user demo)
def _group(name):
    gs = list(ws().groups.list(filter=f'displayName eq "{name}"'))
    return gs[0] if gs else None


def set_membership(member: bool):
    w = ws()
    me = w.current_user.me()
    for g in GOV_GROUPS:
        grp = _group(g)
        if member:
            op = iam.Patch(op=iam.PatchOp.ADD, value={"members": [{"value": me.id}]})
        else:
            op = iam.Patch(op=iam.PatchOp.REMOVE, path=f'members[value eq "{me.id}"]')
        w.groups.patch(grp.id, operations=[op],
                       schemas=[iam.PatchSchema.URN_IETF_PARAMS_SCIM_API_MESSAGES_2_0_PATCH_OP])
    # wait until the SQL engine sees the change
    want = "true" if member else "false"
    for _ in range(60):
        df = sql("SELECT cast(is_member('legal_admins') AS STRING) a, cast(is_member('legal_reviewers_full') AS STRING) f")
        if df.iloc[0]["a"] == want and df.iloc[0]["f"] == want:
            return df
        time.sleep(10)
    raise RuntimeError("group membership change not visible to SQL after 10 minutes")


# ---------------------------------------------------------------- phase 1
def governance_md(skip_restricted=False):
    me = ws().current_user.me().user_name
    out = header("01 - Unity Catalog governance")
    out += ("Groups `legal_admins`, `legal_reviewers`, `legal_reviewers_full` exist in this workspace as "
            "**workspace-local** groups (the workspace user cannot create account groups). `is_member()` "
            "evaluates them inside the column masks / row filters below; UC `GRANT` to workspace-local groups "
            "is rejected, which is recorded in the governance log.\n\n")
    out += section("Governance statement log (latest run of each statement)", """
SELECT section, status, statement, error, ts FROM (
  SELECT *, row_number() OVER (PARTITION BY section, statement ORDER BY ts DESC) rn
  FROM ${catalog}.curated.governance_log) WHERE rn = 1 ORDER BY section DESC, ts""", max_col_chars=120)
    out += section("SHOW GRANTS ON CATALOG", f"SHOW GRANTS ON CATALOG {CATALOG}")
    out += section("SHOW GRANTS ON SCHEMA curated", f"SHOW GRANTS ON SCHEMA {CATALOG}.curated")
    out += section("Mask / row-filter functions", f"SHOW USER FUNCTIONS IN {CATALOG}.curated")
    out += section("Mask / row-filter function definitions (information_schema.routines)", f"""
SELECT routine_name, data_type AS returns, routine_definition, comment
FROM {CATALOG}.information_schema.routines WHERE routine_schema = 'curated' ORDER BY routine_name""", max_col_chars=400)
    for t in ["gold_clauses", "gold_documents", "gold_risk_flags", "silver_parsed"]:
        out += section(f"DESCRIBE TABLE EXTENDED curated.{t} (column masks, row filter, tags)",
                       f"DESCRIBE TABLE EXTENDED {CATALOG}.curated.{t}", max_col_chars=220)
    out += section("Tags from information_schema (column tags)", f"""
SELECT schema_name, table_name, column_name, tag_name, tag_value
FROM {CATALOG}.information_schema.column_tags ORDER BY table_name, column_name""")
    out += section("Tags from information_schema (schema tags)", f"""
SELECT schema_name, tag_name, tag_value FROM {CATALOG}.information_schema.schema_tags""")
    out += section("Synthetic user -> matter_team mapping used by the row filter",
                   f"SELECT * FROM {CATALOG}.curated.user_team_mapping ORDER BY matter_team, user_email")

    probe = f"""SELECT matter_team, count(*) AS docs, min(party_name) AS sample_party_name
FROM {CATALOG}.curated.gold_documents GROUP BY matter_team ORDER BY matter_team"""
    probe2 = f"""SELECT clause_type, extracted_value, party_name, matter_team
FROM {CATALOG}.curated.gold_clauses WHERE clause_type IN ('parties', 'governing_law') ORDER BY doc_id, clause_type LIMIT 6"""
    totals = f"""SELECT (SELECT count(*) FROM {CATALOG}.curated.gold_documents) AS gold_documents_rows,
       (SELECT count(*) FROM {CATALOG}.curated.gold_clauses) AS gold_clauses_rows,
       (SELECT count(*) FROM {CATALOG}.curated.gold_risk_flags) AS gold_risk_flags_rows"""
    ident = "SELECT current_user() AS user, is_member('legal_admins') AS in_legal_admins, is_member('legal_reviewers_full') AS in_legal_reviewers_full"

    out += "## Same SELECT as admin vs restricted user\n\n"
    out += (f"The restricted run uses the same identity (`{me}`) after removing it from `legal_admins` and "
            "`legal_reviewers_full` via the SCIM API (it remains mapped to Team Atlas and Team Borealis only). "
            "Membership is restored afterwards. Rows that disappear and `Party ***` values come from the UC row "
            "filter and column masks, not from the query.\n\n")
    set_membership(True)
    out += "### A. Admin (member of legal_admins + legal_reviewers_full)\n\n"
    for t, q in [("identity", ident), ("row counts", totals), ("documents by matter team", probe), ("clause sample", probe2)]:
        out += section(f"A - {t}", q)
    if skip_restricted:
        out += "_Restricted run skipped (--skip-restricted)._\n"
    else:
        try:
            set_membership(False)
            out += "### B. Restricted (not in legal_admins / legal_reviewers_full)\n\n"
            for t, q in [("identity", ident), ("row counts", totals), ("documents by matter team", probe), ("clause sample", probe2)]:
                out += section(f"B - {t}", q)
        finally:
            set_membership(True)
            out += f"\n_Membership restored at {now()}._\n"
    write("01_uc_governance.md", out)


def pipeline_id():
    for p in ws().pipelines.list_pipelines():
        if PIPELINE_NAME in (p.name or ""):
            return p.pipeline_id, p.name
    raise RuntimeError("pipeline not found")


TABLES = ["raw.bronze_documents", "curated.silver_parsed", "curated.int_doc_classified",
          "curated.int_doc_extracted", "curated.int_clauses", "curated.int_risk_flags",
          "curated.gold_documents", "curated.gold_clauses", "curated.gold_risk_flags", "curated.gold_cost_metrics"]


def pipeline_md():
    pid, name = pipeline_id()
    w = ws()
    ups = w.pipelines.list_updates(pid, max_results=5).updates or []
    out = header("02 - Lakeflow pipeline run")
    out += f"Pipeline: `{name}` (id `{pid}`)\n\n### Recent updates (Pipelines API)\n\n"
    rows = []
    for u in ups:
        ts = datetime.datetime.fromtimestamp(u.creation_time / 1000, datetime.timezone.utc).strftime("%Y-%m-%d %H:%M:%S") if u.creation_time else ""
        rows.append({"update_id": u.update_id, "state": u.state.value if u.state else "", "cause": u.cause.value if u.cause else "",
                     "full_refresh": u.full_refresh, "created_utc": ts})
    import pandas as pd
    out += md(pd.DataFrame(rows)) + "\n\n"
    latest_ok = next((u.update_id for u in ups if u.state and u.state.value == "COMPLETED"), None)
    out += f"Latest COMPLETED update: `{latest_ok}`\n\n"
    out += section("Expectation results per dataset (event log, all updates)", f"""
WITH ev AS (
  SELECT origin.update_id, origin.flow_name,
         explode(from_json(details:flow_progress.data_quality.expectations::string,
                 'array<struct<name:string,dataset:string,passed_records:bigint,failed_records:bigint>>')) AS e
  FROM event_log('{pid}')
  WHERE event_type = 'flow_progress' AND details:flow_progress.data_quality.expectations IS NOT NULL)
SELECT update_id, e.dataset, e.name AS expectation, sum(e.passed_records) AS passed, sum(e.failed_records) AS failed
FROM ev GROUP BY ALL ORDER BY update_id, dataset, expectation""")
    out += section("Flow completion events for the latest completed update", f"""
SELECT timestamp, origin.flow_name, details:flow_progress.status::string AS status,
       details:flow_progress.metrics.num_output_rows::bigint AS num_output_rows
FROM event_log('{pid}')
WHERE event_type = 'flow_progress' AND origin.update_id = '{latest_ok}'
  AND details:flow_progress.status::string IN ('COMPLETED', 'FAILED')
ORDER BY timestamp""")
    out += section("Update state transitions (latest completed update)", f"""
SELECT timestamp, message FROM event_log('{pid}')
WHERE event_type = 'update_progress' AND origin.update_id = '{latest_ok}' ORDER BY timestamp""")
    union = "\nUNION ALL ".join(f"SELECT '{t}' AS table_name, count(*) AS row_count FROM {CATALOG}.{t}" for t in TABLES)
    out += section("Row counts (queried as admin)", union)
    out += section("Parse status / truncation", f"""
SELECT (SELECT count(*) FROM {CATALOG}.raw.bronze_documents) AS bronze_docs,
       (SELECT count(*) FROM {CATALOG}.curated.silver_parsed) AS parsed_ok_docs,
       (SELECT sum(page_count) FROM {CATALOG}.curated.silver_parsed) AS pages,
       (SELECT count(*) FROM {CATALOG}.curated.silver_parsed WHERE parse_error IS NOT NULL) AS docs_with_page_errors,
       (SELECT count_if(truncated) FROM {CATALOG}.curated.int_doc_extracted) AS truncated_docs""")
    out += section("Idempotency check: duplicate keys after repeated setup_job / pipeline runs (expect 0)", f"""
SELECT (SELECT count(*) - count(DISTINCT doc_id) FROM {CATALOG}.raw.bronze_documents) AS dup_bronze_doc_ids,
       (SELECT count(*) - count(DISTINCT doc_id) FROM {CATALOG}.curated.silver_parsed) AS dup_silver_doc_ids,
       (SELECT count(*) - count(DISTINCT clause_id) FROM {CATALOG}.curated.gold_clauses) AS dup_clause_ids,
       (SELECT count(*) - count(DISTINCT flag_id) FROM {CATALOG}.curated.gold_risk_flags) AS dup_flag_ids""")
    out += section("gold_cost_metrics", f"SELECT * FROM {CATALOG}.curated.gold_cost_metrics ORDER BY run_id, stage")
    out += ("_Cost note: AI Functions do not return token usage, so tokens are estimated as characters/4 and "
            "unit prices are illustrative configuration values in `resources/pipeline.yml`._\n")
    write("02_pipeline_run.md", out)


def samples_md():
    out = header("03 - Sample outputs (10 real rows each, queried as admin)")
    out += section("gold_documents", f"""
SELECT doc_id, title, contract_type, round(contract_type_confidence, 2) AS type_conf, page_count, truncated, matter_id, matter_team
FROM {CATALOG}.curated.gold_documents ORDER BY doc_id LIMIT 10""", max_col_chars=70)
    out += section("Contract type distribution", f"""
SELECT contract_type, count(*) AS docs, round(avg(contract_type_confidence), 3) AS avg_conf
FROM {CATALOG}.curated.gold_documents GROUP BY ALL ORDER BY docs DESC""")
    out += section("gold_clauses", f"""
SELECT substr(doc_id, 1, 10) AS doc, clause_type, extracted_value, normalized_value, round(confidence, 2) AS conf, source_snippet
FROM {CATALOG}.curated.gold_clauses
WHERE clause_type IN ('governing_law', 'auto_renewal', 'notice_period_days', 'liability_cap', 'uncapped_liability', 'expiration_date')
ORDER BY doc_id, clause_type LIMIT 10""", max_col_chars=140)
    out += section("Clause coverage by type", f"""
SELECT clause_type, count(*) AS clauses, round(avg(confidence), 3) AS avg_conf
FROM {CATALOG}.curated.gold_clauses GROUP BY ALL ORDER BY clause_type""")
    out += section("gold_risk_flags (with AI-written explanations)", f"""
SELECT substr(doc_id, 1, 10) AS doc, rule_id, severity, clause_type, explanation, explanation_error
FROM {CATALOG}.curated.gold_risk_flags
WHERE severity IN ('high', 'medium') ORDER BY severity, doc_id LIMIT 10""", max_col_chars=400)
    out += section("Flags by severity and rule", f"""
SELECT severity, rule_id, count(*) AS flags, count(explanation) AS with_explanation
FROM {CATALOG}.curated.gold_risk_flags GROUP BY ALL ORDER BY severity, rule_id""")
    write("03_sample_outputs.md", out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--phase", nargs="*", type=int, default=[1])
    ap.add_argument("--skip-restricted", action="store_true")
    a = ap.parse_args()
    os.makedirs(EVID, exist_ok=True)
    if 1 in a.phase:
        pipeline_md()
        samples_md()
        governance_md(a.skip_restricted)


if __name__ == "__main__":
    main()
